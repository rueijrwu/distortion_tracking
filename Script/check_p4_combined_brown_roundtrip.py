"""Audit frozen order-2 P4 model forward equivalence and all held-out round trips."""
from __future__ import annotations
import json
from pathlib import Path
import sys
import numpy as np

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'data/p4_combined_brown/baseline_check'))
import combined_core as core
import p4_combined_brown_model as model

OUT=ROOT/'data/p4_combined_brown/final_checks'
OUT.mkdir(parents=True,exist_ok=True)

def main():
    G=core.load_data()
    order,c=model.load_coefficients()
    if order!=2: raise AssertionError(order)
    ai,ti,bi=np.indices((21,101,101))
    held=((ti%2!=0)|(bi%2!=0))
    ix=np.flatnonzero(held.ravel())
    a=G['A'][ai.ravel()[ix]]; ade=G['ADE'][ti.ravel()[ix]]; bde=G['BDE'][bi.ravel()[ix]]
    r0=np.broadcast_to(G['r0'][None,model.OUTER,:],(len(ix),8,2)).copy()
    measured=G['real'][ai.ravel()[ix],ti.ravel()[ix],bi.ravel()[ix]][:,model.OUTER,:]
    pred,den=model.forward(r0,a,ade,bde,(order,c),True)
    ref,coreden=core.predict_model(G,c.ravel(),order,'C1',ix)
    forward_diff=np.max(np.abs(pred-ref[:,model.OUTER,:]))*1000
    recovered,iden=model.inverse(pred,a,ade,bde,(order,c),True)
    err=(recovered-np.broadcast_to(r0,recovered.shape))*1000
    absnorm=np.linalg.norm(err,axis=-1)
    values={
      'heldout_states':int(len(ix)), 'fields_per_state':8,
      'heldout_samples':int(err.shape[0]*err.shape[1]),
      'forward_core_max_abs_difference_um':float(forward_diff),
      'roundtrip_max_point_um':float(absnorm.max()),
      'roundtrip_rms_coordinate_um':float(np.sqrt(np.mean(err**2))),
      'roundtrip_rms_point_um':float(np.sqrt(np.mean(absnorm**2))),
      'min_forward_projective_denominator':float(den.min()),
      'min_inverse_projective_denominator':float(iden.min()),
      'core_min_forward_denominator':float(np.min(coreden)),
      'coefficient_order':order, 'coefficient_shape':list(c.shape),
      'grid_sha256':G['sha256']}
    # Small API shape and identity checks use the same frozen coefficients.
    single=model.forward(G['r0'],0.,0.,0.,(order,c))
    single_inv=model.inverse(single,0.,0.,0.,(order,c))
    values['single_forward_shape']=list(single.shape)
    values['single_inverse_shape']=list(single_inv.shape)
    values['A0_baseline_max_abs_um']=float(np.max(np.abs(single-G['r0']))*1000)
    values['single_roundtrip_max_abs_um']=float(np.max(np.abs(single_inv-G['r0']))*1000)
    (OUT/'roundtrip_metrics.json').write_text(json.dumps(values,indent=2)+'\n',encoding='utf-8')
    lines=['# P4 combined Brown model round-trip audit','',
      'Generated by `Script/check_p4_combined_brown_roundtrip.py`. Frozen order-2 coefficients only; no fitting. Coordinates are millimetres at the API and errors below are micrometres.', '',
      f"Held-out set: {len(ix):,} states = 7,600 complement-of-even/even states per accommodation × 21 accommodations; eight non-center fields per state ({err.shape[0]*err.shape[1]:,} point round trips).",
      f"Input grid SHA-256: `{G['sha256']}`. Source coefficients: `data/p4_combined_brown/baseline_check/combined_model_order2_1.npz`.", '',
      '| Check | Result |','|---|---:|',
      f"| Forward max absolute difference vs `combined_core.predict_model` | {values['forward_core_max_abs_difference_um']:.12g} µm |",
      f"| Round-trip max point error | {values['roundtrip_max_point_um']:.9g} µm |",
      f"| Round-trip RMS point error | {values['roundtrip_rms_point_um']:.9g} µm |",
      f"| Round-trip RMS coordinate error | {values['roundtrip_rms_coordinate_um']:.9g} µm |",
      f"| Minimum forward projective denominator | {values['min_forward_projective_denominator']:.12g} |",
      f"| Minimum inverse projective denominator | {values['min_inverse_projective_denominator']:.12g} |", '',
      'The forward check compares the standalone public API with the project fitting core. The inverse recovers the fixed A=0 real-ray reference coordinates: it numerically removes radial r² and Brown-Conrady, algebraically solves the projective homography, then numerically applies B_A inverse. Newton iterations are fixed-count (30 for gaze distortion, 12 for radial barrel); this artifact records the resulting full-domain errors.']
    (OUT/'roundtrip_report.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print(json.dumps(values,indent=2))

if __name__=='__main__': main()
